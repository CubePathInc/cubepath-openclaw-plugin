// Rebuilds tool-policy.js from the live MCP server. Use a token holding every scope:
// tools/list only returns what the token can use, and a missing tool falls back to
// needing critical approval.
import { writeFileSync } from "node:fs";

const token = process.env.CUBEPATH_API_TOKEN;
if (!token) throw new Error("Set CUBEPATH_API_TOKEN");

const response = await fetch("https://mcp.cubepath.com/mcp", {
  method: "POST",
  headers: { "content-type": "application/json", accept: "application/json", authorization: `Bearer ${token}` },
  body: JSON.stringify({ jsonrpc: "2.0", id: 1, method: "tools/list" }),
});
if (!response.ok) throw new Error(`tools/list failed: HTTP ${response.status}`);
const { result, error } = await response.json();
if (error) throw new Error(`tools/list failed: ${error.message}`);

const names = (keep) => JSON.stringify(result.tools.filter(keep).map((t) => t.name).sort(), null, 2);
const readOnly = (t) => t.annotations?.readOnlyHint === true;
const destructive = (t) => t.annotations?.destructiveHint === true;

writeFileSync(
  new URL("../tool-policy.js", import.meta.url),
  `// Generated by scripts/sync-tool-policy.mjs. Do not edit by hand.
export const READ_ONLY_TOOLS = new Set(${names(readOnly)});

export const WRITE_TOOLS = new Set(${names((t) => !readOnly(t) && !destructive(t))});

export const DESTRUCTIVE_TOOLS = new Set(${names((t) => !readOnly(t) && destructive(t))});
`,
);
console.log(`Synced ${result.tools.length} tools`);
